using JuMP

"""
    build_etamac_model(; optimizer=nothing, set_starts=true)

Modelo JuMP convertido do GAMS `etamac`.
"""
function build_etamac_model(; optimizer=nothing, set_starts::Bool=true)
    model = optimizer === nothing ? Model() : Model(optimizer)

    @variable(model, x[1:97])
    @variable(model, objvar)

    A = 0.8153726976
    B = 0.306708090151268
    pK = -0.342222222222222
    pC = -0.427777777777778
    pL = -0.794444444444445
    pAgg = -0.818181818181818

    # Bounds
    fix(x[1], 12.32657617084; force=true)
    for i in 2:9
        set_lower_bound(x[i], 10.9)
    end
    for i in 10:17
        set_lower_bound(x[i], 1.0317041301)
    end
    for i in 18:26
        set_lower_bound(x[i], 4.25)
    end
    lbs_27_34 = [0.508311836408595, 0.589272733608307, 0.683128602764001,
                 0.79193327859709, 0.918067718453005, 1.06429210445432,
                 1.23380624417608, 1.43031959158279]
    for (k, lb) in enumerate(lbs_27_34)
        set_lower_bound(x[26+k], lb)
    end
    for i in 35:43
        set_lower_bound(x[i], 2.5)
    end
    lbs_44_52 = [0.257926032525, 0.299006962593291, 0.346631019769593,
                 0.401840354567059, 0.465843105057112, 0.540039834384121,
                 0.626054179090777, 0.725768378927107, 0.841364465636933]
    for (k, lb) in enumerate(lbs_44_52)
        set_lower_bound(x[43+k], lb)
    end
    for i in 53:61
        set_lower_bound(x[i], 50.0)
    end
    lbs_62_70 = [5.1585206505, 5.98013925186582, 6.93262039539185,
                 8.03680709134119, 9.31686210114223, 10.8007966876824,
                 12.5210835818155, 14.5153675785421, 16.8272893127387]
    for (k, lb) in enumerate(lbs_62_70)
        set_lower_bound(x[61+k], lb)
    end
    for i in 71:79
        set_lower_bound(x[i], 3.2)
    end
    for i in 80:88
        set_lower_bound(x[i], 0.7)
    end

    if set_starts
        # Chutes do GAMS quando fornecidos; nos demais, usa-se o limite inferior positivo.
        given = Dict{Int,Float64}(
            1=>12.32657617084,
            2=>14.6486885348509, 3=>16.9818448409483, 4=>19.6866124578966,
            5=>22.8221794332309, 6=>26.4571609359673, 7=>30.6711007526496,
            8=>35.5562119327899, 9=>41.2193946739997,
            18=>4.926914815775, 19=>5.71164461221252, 20=>6.62136152055325,
            21=>7.67597274734501, 22=>8.89855620103042, 23=>10.3158655025561,
            24=>11.958915431079, 25=>13.8636606159961, 26=>16.0717823270182,
            35=>2.89818518575, 36=>3.35979094836031, 37=>3.89491854150191,
            38=>4.51527808667354, 39=>5.23444482413554, 40=>6.06815617797415,
            41=>7.03465613592881, 42=>8.15509447999769, 43=>9.45398960412836,
            53=>57.963703715, 54=>67.1958189672061, 55=>77.8983708300382,
            56=>90.3055617334707, 57=>104.688896482711, 58=>121.363123559483,
            59=>140.693122718576, 60=>163.101889599954, 61=>189.079792082567,
            71=>3.70967703776, 72=>4.30053241390119, 73=>4.98549573312245,
            74=>5.77955595094213, 75=>6.70008937489349, 76=>7.76723990780692,
            77=>9.00435985398888, 78=>10.438520934397, 79=>12.1011066932843,
            80=>0.81149185201, 81=>0.940741465540885, 82=>1.09057719162054,
            83=>1.26427786426859, 84=>1.46564455075795, 85=>1.69908372983276,
            86=>1.96970371806007, 87=>2.28342645439935, 88=>2.64711708915594
        )
        for i in 1:97
            if haskey(given, i)
                set_start_value(x[i], given[i])
            elseif has_lower_bound(x[i])
                set_start_value(x[i], max(1.05 * lower_bound(x[i]), lower_bound(x[i]) + 1e-6))
            else
                set_start_value(x[i], 0.0)
            end
        end
        set_start_value(objvar, -10.0)
    end

    coeff = [0.820744282617518, 0.7206494796327, 0.632761852252708,
             0.555592660485018, 0.487834725317074, 0.428340286240339,
             0.376101559185243, 0.330233665535262]

    @constraint(model, e_prod[t in 1:8], x[9+t] - 4.91287681*x[79+t] == 0.0)

    @constraint(model, e_agg[t in 1:8],
        -(coeff[t]*x[9+t]^pK + B*x[44+t]^pC*x[62+t]^pL)^pAgg + x[26+t] == 0.0)

    @constraint(model, e17, -x[35] + x[44] == -2.038431744)
    @constraint(model, e_inv_cap[t in 1:8], A*x[34+t] - x[35+t] + x[44+t] == 0.0)

    @constraint(model, e26, -x[53] + x[62] == -40.76863488)
    @constraint(model, e_inv_lab[t in 1:8], A*x[52+t] - x[53+t] + x[62+t] == 0.0)

    @constraint(model, e_cap_dyn[t in 1:8], -A*x[t] + x[t+1] - x[9+t] == 0.0)

    @constraint(model, e43,
        -(0.612508399277048 + B*x[44]^pC*x[62]^pL)^pAgg + x[18] == 3.4653339648)

    @constraint(model, e_out_dyn[t in 1:8], -A*x[17+t] + x[18+t] - x[26+t] == 0.0)

    c1 = [52.550502505, 55.2311062705602, 58.0484477684999, 61.0095019973984,
          64.1215997508617, 67.3924457666453, 70.8301378015635,
          74.4431866794111, 78.2405373615315]
    c2 = [4.9683636144, 5.48547488997641, 6.05640752245858, 6.68676328190259,
          7.38272697509128, 8.15112712846509, 8.99950298698105,
          9.93617848626683, 10.970343923856]
    @constraint(model, e_invest[t in 1:9], -c1[t]*x[34+t] - c2[t]*x[52+t] + 1000.0*x[88+t] == 0.0)

    @constraint(model, e_resource[t in 1:9], x[17+t] - x[70+t] - x[79+t] - x[88+t] == 0.0)
    @constraint(model, e70, 0.07*x[9] - x[88] <= 0.0)

    w = [0.8153726976, 0.664832635991501, 0.542086379860909,
         0.442002433879407, 0.360396716858018, 0.293857643230706,
         0.239603499271399, 0.19536615155532, 3.98240565033479]
    @constraint(model, e71, -sum(w[t]*log(x[70+t]) for t in 1:9) - objvar == 0.0)

    @objective(model, Min, objvar)

    return model
end

model = build_etamac_model()
