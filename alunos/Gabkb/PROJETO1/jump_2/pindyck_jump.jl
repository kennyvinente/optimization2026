# pindyck_jump.jl
# Modelo pindyck convertido de GAMS Convert para JuMP em forma compacta.

using JuMP

function build_pindyck_model(; optimizer=nothing, set_starts::Bool=true)
    model = optimizer === nothing ? Model() : Model(optimizer)

    @variable(model, x[1:116])
    @variable(model, objvar)

    # Variáveis positivas no GAMS. Para divisores, usa-se guarda pequena de domínio.
    positive_idx = vcat(1:16, 18:33, 35:50, 52:83, 85:100)
    for i in positive_idx
        set_lower_bound(x[i], 0.0)
    end
    for i in 85:100
        set_lower_bound(x[i], 1e-8)
    end

    fix(x[17], 18.0; force=true)
    fix(x[34], 6.5; force=true)
    fix(x[51], 0.0; force=true)
    fix(x[84], 500.0; force=true)

    if set_starts
        starts = Dict{Int,Float64}(
            1=>14.0, 2=>14.0, 3=>14.0, 4=>14.0, 5=>14.0, 6=>14.0, 7=>14.0, 8=>14.0,
            9=>14.0, 10=>14.0, 11=>14.0, 12=>14.0, 13=>14.0, 14=>14.0, 15=>14.0, 16=>14.0,
            18=>18.0, 19=>18.0, 20=>18.0, 21=>18.0, 22=>18.0, 23=>18.0, 24=>18.0, 25=>18.0,
            26=>18.0, 27=>18.0, 28=>18.0, 29=>18.0, 30=>18.0, 31=>18.0, 32=>18.0, 33=>18.0,
            35=>7.0, 36=>7.0, 37=>7.0, 38=>7.0, 39=>7.0, 40=>7.0, 41=>7.0, 42=>7.0,
            43=>7.0, 44=>7.0, 45=>7.0, 46=>7.0, 47=>7.0, 48=>7.0, 49=>7.0, 50=>7.0,
            52=>7.0, 53=>14.0, 54=>21.0, 55=>28.0, 56=>35.0, 57=>42.0, 58=>49.0, 59=>56.0,
            60=>63.0, 61=>70.0, 62=>77.0, 63=>84.0, 64=>91.0, 65=>98.0, 66=>105.0, 67=>112.0,
            68=>11.0, 69=>11.0, 70=>11.0, 71=>11.0, 72=>11.0, 73=>11.0, 74=>11.0, 75=>11.0,
            76=>11.0, 77=>11.0, 78=>11.0, 79=>11.0, 80=>11.0, 81=>11.0, 82=>11.0, 83=>11.0,
            85=>489.0, 86=>478.0, 87=>467.0, 88=>456.0, 89=>445.0, 90=>434.0, 91=>423.0, 92=>412.0,
            93=>401.0, 94=>390.0, 95=>379.0, 96=>368.0, 97=>357.0, 98=>346.0, 99=>335.0, 100=>324.0
        )
        for (i, v) in starts
            set_start_value(x[i], v)
        end
    end

    rhs = [
        3.3, 3.3345, 3.3695175, 3.4050602625, 3.4411361664375, 3.47775320893406,
        3.51491950706807, 3.55264329967409, 3.5909329491692, 3.62979694340674,
        3.66924389755784, 3.70928255602121, 3.74992179436153, 3.79117062127695,
        3.8330381805961, 3.87553375330505
    ]
    disc = [
        1.0, 0.952380952380952, 0.90702947845805, 0.863837598531476,
        0.822702474791882, 0.783526166468459, 0.746215396636628,
        0.710681330130121, 0.676839362028687, 0.644608916217797,
        0.613913253540759, 0.584679289086437, 0.556837418177559,
        0.530321350645295, 0.505067952995519, 0.48101709809097
    ]

    for t in 1:16
        @constraint(model, 0.13*x[t] - 0.87*x[16+t] + x[17+t] == rhs[t])
        @constraint(model, -(1.1 + 0.1*x[t]) * 1.02^(-0.142857142857143*x[51+t]) - 0.75*x[33+t] + x[34+t] == 0)
        @constraint(model, -x[34+t] - x[50+t] + x[51+t] == 0)
        @constraint(model, -x[17+t] + x[34+t] + x[67+t] == 0)
        @constraint(model, x[67+t] - x[83+t] + x[84+t] == 0)
        @constraint(model, -x[67+t]*(x[t] - 250/x[84+t]) + x[100+t] == 0)
    end

    @constraint(model, -sum(disc[t] * x[100+t] for t in 1:16) - objvar == 0)
    @objective(model, Min, objvar)
    return model, x, objvar
end

model, x, objvar = build_pindyck_model()
for i in 1:116
    @eval $(Symbol(:x, i)) = x[$i]
end
