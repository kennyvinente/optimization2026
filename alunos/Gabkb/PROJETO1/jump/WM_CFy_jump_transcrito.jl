function build_WM_CFy_model(; seed::Int = 1234)
    model = Model()

    # --------------------------------------------------------
    # Variáveis
    # AMPL original:
    # var alpha{1..Nu,1..2} := Uniform(-pi,pi);
    # var x{i in 0..N-1,j in 1..2} := 1;
    # var z{i in 0..N,j in 1..M} := 1;
    # var y{i in 0..2*N-1, j in 1..2} := 1;
    # var t;
    # --------------------------------------------------------

    @variable(model, alpha[1:Nu, 1:2])
    @variable(model, x[0:N-1, 1:2], start = 1.0)
    @variable(model, z[0:N, 1:M], start = 1.0)
    @variable(model, y[0:2*N-1, 1:2], start = 1.0)
    @variable(model, t, start = bd)

    Random.seed!(seed)

    for u in 1:Nu
        for j in 1:2
            set_start_value(alpha[u, j], -pi_const + 2.0*pi_const*rand())
        end
    end

    # --------------------------------------------------------
    # Objetivo
    # --------------------------------------------------------

    @objective(model, Min, t)

    # --------------------------------------------------------
    # Expressões RMS
    # Transcrição fiel do AMPL, sem epsilon artificial.
    # Como y inicia em 1.0, o RMS inicial não é zero.
    # --------------------------------------------------------

    @NLexpression(
        model,
        rms_y1,
        sqrt((1.0 / N) * sum(y[i, 1]^2 for i in N:2*N-1))
    )

    @NLexpression(
        model,
        rms_y2,
        sqrt((1.0 / N) * sum(y[i, 2]^2 for i in N:2*N-1))
    )

    # --------------------------------------------------------
    # Restrições de limite em y usando t
    # --------------------------------------------------------

    @NLconstraint(model, bound31[j in N:2*N-1], -t*rms_y1 <= y[j, 1])
    @NLconstraint(model, bound32[j in N:2*N-1],  y[j, 1] <= t*rms_y1)

    @NLconstraint(model, bound41[j in N:2*N-1], -t*rms_y2 <= y[j, 2])
    @NLconstraint(model, bound42[j in N:2*N-1],  y[j, 2] <= t*rms_y2)

    @constraint(model, bound51[j in N:2*N-1],  y[j, 1] <= bd)
    @constraint(model, bound52[j in N:2*N-1], -bd <= y[j, 1])

    @constraint(model, bound61[j in N:2*N-1],  y[j, 2] <= bd)
    @constraint(model, bound62[j in N:2*N-1], -bd <= y[j, 2])

    # --------------------------------------------------------
    # Entrada senoidal
    # AMPL original usa k[u] = u e pn[i] = i*2*pi/N.
    # --------------------------------------------------------

    @NLconstraint(
        model,
        inp_ch1[i in 0:N-1],
        x[i, 1] == sum(a1[u] * cos((i * 2.0 * pi_const / N) * u + alpha[u, 1]) for u in 1:Nu)
    )

    @NLconstraint(
        model,
        inp_ch2[i in 0:N-1],
        x[i, 2] == sum(a2[u] * cos((i * 2.0 * pi_const / N) * u + alpha[u, 2]) for u in 1:Nu)
    )

    # --------------------------------------------------------
    # Dinâmica de estado
    # z[i] = A*z[i-1] + B*x[i-1]
    # --------------------------------------------------------

    @constraint(
        model,
        out1[i in 1:N, j in 1:M],
        z[i, j] ==
        sum(A[j, l] * z[i-1, l] for l in 1:M)
        +
        sum(B[j, l] * x[i-1, l] for l in 1:2)
    )

    # --------------------------------------------------------
    # Saída y no primeiro período
    # --------------------------------------------------------

    @constraint(
        model,
        out2[i in 1:N, j in 1:2],
        y[i, j] == sum(C[j, l] * z[i, l] for l in 1:M)
    )

    # --------------------------------------------------------
    # Saída y no segundo período
    # --------------------------------------------------------

    @constraint(
        model,
        out3[i in N+1:2*N-1, j in 1:2],
        y[i, j] == sum(C[j, l] * z[i-N-1, l] for l in 1:M)
    )

    # --------------------------------------------------------
    # Restrições de variação em x
    # --------------------------------------------------------

    @constraint(model, move1[i in 0:N-2, j in 1:2], -mx <= x[i+1, j] - x[i, j])
    @constraint(model, move2[j in 1:2], -mx <= x[0, j] - x[N-1, j])

    @constraint(model, move3[i in 0:N-2, j in 1:2], x[i+1, j] - x[i, j] <= mx)
    @constraint(model, move4[j in 1:2], x[0, j] - x[N-1, j] <= mx)

    # --------------------------------------------------------
    # Restrições de variação em y
    # --------------------------------------------------------

    @constraint(model, movey[i in N-1:2*N-2, j in 1:2], -my <= y[i+1, j] - y[i, j])
    @constraint(model, movey1[i in N-1:2*N-2, j in 1:2], y[i+1, j] - y[i, j] <= my)

    return model
end

