using JuMP

# ============================================================
# cont5_2_1_l_jump.jl
# Tradução manual do arquivo cont5_2_1_l.mod para JuMP
# ============================================================

model = Model()

# ------------------------------------------------------------
# Parâmetros
# ------------------------------------------------------------

n = 300
m = 300

n1 = n - 1
m1 = m - 1

dx = 1.0 / n

T = 1.58
dt = T / m

h2 = dx^2

a = 0.001



# ------------------------------------------------------------
# Variáveis
# ------------------------------------------------------------

@variable(model, 0.0 <= y[0:m, 0:n] <= 1.0)
@variable(model, -1.0 <= u[1:m] <= 1.0)

# ------------------------------------------------------------
# Valores iniciais
# ------------------------------------------------------------

for i in 0:m
    for j in 0:n
        set_start_value(y[i,j], 0.0)
    end
end

for i in 1:m
    set_start_value(u[i], 0.0)
end

# ------------------------------------------------------------
# Função objetivo
#
# yt[j] = 0.5 * (1 - (j*dx)^2)
# ------------------------------------------------------------

@NLobjective(
    model,
    Min,
    0.25 * dx * (
        (y[m,0] - 0.5*(1.0 - (0.0*dx)^2))^2 +
        2.0 * sum(
            (y[m,j] - 0.5*(1.0 - (j*dx)^2))^2
            for j in 1:n1
        ) +
        (y[m,n] - 0.5*(1.0 - (n*dx)^2))^2
    )
    +
    0.25 * a * dt * (
        2.0 * sum(u[i]^2 for i in 1:m1) +
        u[m]^2
    )
)

# ------------------------------------------------------------
# PDE discreta
# ------------------------------------------------------------

@NLconstraint(
    model,
    pde[i in 0:m1, j in 1:n1],
    (y[i+1,j] - y[i,j]) / dt == 0.5 * (
    y[i,j-1] - 2.0*y[i,j] + y[i,j+1] +
    y[i+1,j-1] - 2.0*y[i+1,j] + y[i+1,j+1]
) / h2

)

# ------------------------------------------------------------
# Condição inicial
# ------------------------------------------------------------

@constraint(
    model,
    ic[j in 0:n],
    y[0,j] == 0.0
)

# ------------------------------------------------------------
# Condições de contorno
# ------------------------------------------------------------

@constraint(
    model,
    bc1[i in 1:m],
    y[i,2] - 4.0*y[i,1] + 3.0*y[i,0] == 0.0
)

@NLconstraint(
    model,
    bc2[i in 1:m],
    (y[i,n-2] - 4.0*y[i,n1] + 3.0*y[i,n]) / (2.0*dx) == u[i] - y[i,n]
)

println("Modelo cont5_2_1_l carregado com sucesso.")
println("Variáveis: ", num_variables(model))
println("Restrições: ", num_constraints(model; count_variable_in_set_constraints = true))
